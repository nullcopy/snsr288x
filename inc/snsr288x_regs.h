/*******************************************************************************
 * Register Manipulation Macros
 ******************************************************************************/
/**
 * Get a bit field from a register value
 *
 * Example (get PWR_RDY field from the STATUS_1 register):
 * uint8_t reg_val = spi_read(...); // Read the register
 * uint8_t pwr_rdy = SNSR288X_GET_FIELD(STATUS_1, PWR_RDY, reg_val);
 */
#define SNSR288X_GET_FIELD(reg, field, reg_val)                                \
  (((reg_val)&SNSR288X_REG__##reg##__##field##__MASK) >>                       \
   (SNSR288X_REG__##reg##__##field##__SHFT))

/**
 * Set a bit field in a register
 *
 * Example (enable VDD_OOR interrupt in INTERRUPT_ENABLE_1):
 * uint8_t reg_val = spi_read(...); // Read the register
 * reg_val = SNSR288X_SET_FIELD(INTERRUPT_ENABLE_1, VDD_OOR_EN, reg_val, 1u);
 * spi_write(..., reg_val); // Write the modified value
 */
#define SNSR288X_SET_FIELD(reg, field, reg_val, field_val)                     \
  (((reg_val) & ~(SNSR288X_REG__##reg##__##field##__MASK)) |                   \
   (((field_val) << (SNSR288X_REG__##reg##__##field##__SHFT)) &                \
    SNSR288X_REG__##reg##__##field##__MASK))

#define SNSR288X_REG_DEFAULT(reg)                                              \
  snsr288x_reg_defaults[SNSR288X_REG__##reg##__ADDR].value

